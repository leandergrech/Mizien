    if "--xlsx" in argv:
        before = (ROOT / "data" / "candidates.xlsx").read_bytes() if (ROOT / "data" / "candidates.xlsx").is_file() else b""
        write_workbook(records)
        if (ROOT / "data" / "candidates.xlsx").read_bytes() != before:
            changed.append("data/candidates.xlsx")
    print("sheets: " + (", ".join(changed) + " updated" if changed else "all current"))
    return 0


