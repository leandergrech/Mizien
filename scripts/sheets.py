"""The tracker sheets, generated from the claim records so they cannot drift from them.

claims/CC-NNN/claim.yml is the source of truth. This module writes what is derived from it:

  data/claims.csv     the claim sheet: one row per claim (columns of the original tracker)
  data/facts.csv      the fact sheet: every figure recomputed by a check, from data/cc-nnn/checks.csv
  data/actors.csv     bodies and the claims they made, from the register (data/bodies.csv)
  data/themes.csv     only its "Edges generated" column (recounted from data/edges.csv); themes are curated by hand
  README.md           the claims table, between the <!-- claims-table --> markers
  data/candidates.xlsx  the workbook (python scripts/sheets.py --xlsx): every sheet above plus quick checks,
                        patterns, edges, sources, bodies and the queue, for reading in a spreadsheet

Hand-curated, read here but never written: data/edges.csv, data/sources.csv, data/quick_checks.csv,
data/queue.csv, data/bodies.csv, methodology/pattern-tags.md.

scripts/build_site_data.py calls write_text_sheets() on every build, so the CSV sheets and the README table follow
the records. The workbook is binary (it cannot be merged), so it is rebuilt on request, at the end of a session:

    python scripts/sheets.py           # text sheets only
    python scripts/sheets.py --xlsx    # text sheets and data/candidates.xlsx
"""
